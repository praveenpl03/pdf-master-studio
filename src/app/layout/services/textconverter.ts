pdfFontFamily(fontFamily?: string, fontName?: string): string {
    const label = `${fontFamily ?? ''} ${fontName ?? ''}`.toLowerCase();
    
    // Explicit priority check
    if (label.includes('arial') || label.includes('helvetica') || label.includes('sans')) {
        return 'Arial, Helvetica, sans-serif';
    }
    if (label.includes('courier') || label.includes('mono')) {
        return 'Courier New, Courier, monospace';
    }
    // Only default to Times/Cambria if no other indicators are found
    if (label.includes('times') || label.includes('serif') || label.includes('cambria')) {
        return 'Times New Roman, Georgia, serif';
    }
    
    return 'Arial, Helvetica, sans-serif'; // Safer general fallback
}
     isPdfTextItem(item: unknown): item is PdfTextItemLike {
    if (!item || typeof item !== 'object') return false;
    const candidate = item as Partial<PdfTextItemLike>;
    return typeof candidate.str === 'string'
      && candidate.str.trim().length > 0
      && Array.isArray(candidate.transform)
      && typeof candidate.width === 'number'
      && typeof candidate.height === 'number';
  }

