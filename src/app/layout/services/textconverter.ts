 htmlItemsFromMuPdf(
  runs: MuPdfTextItem[],
  pageId:string,
  links:LinkRect[] = []
):HtmlTextItem[] {


 const items:HtmlTextItem[] = [];


 for(
   let index=0;
   index < runs.length;
   index++
 ){

   const run =
     runs[index];


   const text =
     run.text
       ?.replace(/\s+/g,' ')
       .trim();


   if(!text)
     continue;


   const isLinked =
    links.some(link =>
      rectsOverlap(
        {
          x:run.bbox.x,
          y:run.bbox.y,
          width:run.bbox.w,
          height:run.bbox.h
        },
        link
      )
    );



   const font =
     this.cleanMuPdfFont(
       run.fontName
     );




   items.push({

    id:
     `${pageId}-mupdf-${index}`,


    pageId,


    text,


    x:
     run.bbox.x,


    y:
     run.bbox.y,

width:
  Math.max(
    30,
    run.bbox.w + 10
  ),

height:
  Math.max(
    run.size * 1.45,
    run.bbox.h + 4
  ),


// keep original PDF area
originalX:
  run.bbox.x,

originalY:
  run.bbox.y,

originalWidth:
  run.bbox.w,

originalHeight:
  run.bbox.h,



    size:
     run.size,


    fontFamily:
     font,


    fontWeight:
     run.weight,


    fontStyle:
     run.style,


    color:
     isLinked
      ? '#0000ee'
      : '#111111',



    textDecoration:
     isLinked
      ? 'underline'
      : undefined,



    backgroundColor:
      '#ffffff',



    originalText:
      text,


    originalSize:
      run.size,


    originalColor:
     isLinked
      ? '#0000ee'
      : '#111111',


    originalFontWeight:
      run.weight,


    originalFontStyle:
      run.style,



    textAlign:'left'

   });


 }


 return items;

}

private  cleanMuPdfFont(
 font:string
){

 if(!font)
   return 'Times New Roman';


 return font
  .replace(
    /^[A-Z]{6}\+/,
    ''
  )
  .replace(
    '-Bold',
    ''
  );

}

